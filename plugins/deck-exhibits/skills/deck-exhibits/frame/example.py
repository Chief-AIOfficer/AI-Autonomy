"""Образец деки на рамке: титул, слайд с деревом метрики, слайд с матрицей, вопросы.
Запуск: python3 <папка скилла>/frame/example.py [путь/дека.html]
Данные выдуманы. Скопируй файл к себе в папку материала и замени заголовки, данные и источники."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deck import Deck, X  # noqa: E402

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.getcwd(), 'пример_деки', 'дека.html')
d = Deck('Образец деки')
d.title('Выручку нового направления дадут три рычага, и два из них в руках роли', 'Материал к встрече. Образец рамки')

t = 'Гипотеза: выручка направления это клиенты × чек, и у чека нет публичной цифры[1]'
d.slide(t, X.driver_tree({'label': 'Выручка направления [млн ₽]', 'op': '×', 'children': [
    {'label': 'Клиенты [тыс.]', 'op': '×', 'children': [{'label': 'Клиенты компании [тыс.]'},
                                                       {'label': 'Доля, купившая продукт [%]', 'kind': 'assume', 'cls': 'role'}]},
    {'label': 'Чек [тыс. ₽ в год]', 'dashed': True, 'cls': 'role'}]},
    classes={'role': ('рычаг роли', 'accent_pale')}, dashed_label='гипотеза, цифры нет', row_h=72, max_h=d.room(t, sources=[1])),
    sources=[('Годовой отчёт компании, 2025', 'https://example.com/report')])

t = 'Гипотеза: первая волна это две инициативы с быстрым результатом'
d.slide(t, X.matrix_2x2([{'label': 'Метрики продукта', 'x': 0.8, 'y': 0.8}, {'label': 'Кейсы с цифрами', 'x': 0.85, 'y': 0.62},
                         {'label': 'Стандарт для сети', 'x': 0.25, 'y': 0.75}, {'label': 'Обучение команды', 'x': 0.3, 'y': 0.3}],
                        x_label='Скорость первого результата', y_label='Влияние на выручку',
                        quadrants={'tr': ('Первая волна', 'good'), 'tl': ('Вторая волна', 'warn')},
                        ends=('долго', 'быстро'), y_ends=('ниже', 'выше'), height=d.room(t, sources=[1]) - 60),
        sources=['Оценка автора до разговора'])

d.slide('Три вопроса, ответы на которые меняют план', X.points([
    {'icon': 'wallet', 'text': '**Чей бюджет** у направления'},
    {'icon': 'users', 'text': '**Кому подчиняется** роль'},
    {'icon': 'chart-column', 'text': '**Сколько клиентов** уже есть'}], cols=3))
d.build(out)
