if __name__ == '__main__':
    names = sys.argv[1:] or list(DEMOS)
    items = []
    for n in names:
        try:
            ex = DEMOS[n]()
        except (X.FitError, X.DataError) as e:
            print(f'{n}: ОШИБКА {e}')
            continue
        items.append((n, ex))
        print(f'{n}: {ex.w}×{ex.h}, предупреждений {len(ex.warnings)}')
        for w in ex.warnings:
            print('   ', w)
    os.makedirs(OUT, exist_ok=True)
    tag = names[0] if len(names) == 1 else 'demo'
    html = X.sheet(items, os.path.join(OUT, f'{tag}.html'))
    h = sum(ex.h + 140 for _, ex in items) + 60
    X.shot(html, os.path.join(OUT, f'{tag}.png'), 1300, h)
    print(os.path.join(OUT, f'{tag}.png'))
